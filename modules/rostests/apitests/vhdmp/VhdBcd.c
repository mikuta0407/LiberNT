START_TEST(VhdBcd)
{
    VHD_BCD_HOST Host = {0};
    BYTE Buffer[512];
    DWORD Length, i;

    Host.Signature = 0x703D2D80;
    Host.Offset = 0x12D00000;
    Length = VhdBuildBcdDevice(&Host, L"\\t.vhdx", VHD_BCD_APPLICATION_PATH, Buffer, sizeof(Buffer));
    ok(Length == sizeof(MbrDevice), "Length %lu, expected %u\n", Length, (unsigned)sizeof(MbrDevice));
    for (i = 0; i < min(Length, sizeof(MbrDevice)); i++)
    {
        if (Buffer[i] != MbrDevice[i])
            break;
    }
    ok(i == sizeof(MbrDevice), "The element differs at offset 0x%lx\n", i);

    ok(VhdBuildBcdDevice(&Host, L"\\t.vhdx", VHD_BCD_APPLICATION_PATH, Buffer, sizeof(MbrDevice) - 1) == 0,
       "A short buffer was accepted\n");
}
